/**
 * build — Core multi-theme and UI profile CSS/TS compiler for 3-tier DTCG tokens.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  artifactNames,
  buildMultiThemeTokens,
  buildTokens,
  guideFromSpec,
  verifyGeneratedFiles,
} from './compiler.js';
import { EXIT } from './exit-codes.js';
import {
  assertSafeOutDir,
  auditStampMatches,
  checkAuditStamp,
  checkCssProvenance,
  checkSpecBinding,
  decideWrite,
  publishCssOutputs,
  reportWriteRefusal,
  specInputHash,
} from './guard.js';
import { profileFileName, UI_PROFILE_IDS, type UiProfileId } from './profile-registry.js';
import { loadSpecOrError } from './spec.js';
import { semanticDir, semanticThemeFile, tokenSourcePatterns } from './tokens.js';
import type { BuildTokensOptions, Logger } from './types.js';
import { buildUiProfile } from './ui-profiles.js';
import { usageText } from './cli-flags.js';
import { fromCwd, getArg, hasFlag, isMainModule } from './paths.js';

export interface CompileTokensOptions {
  tokensDir: string;
  outDir: string;
  theme?: string | undefined;
  specPath?: string | undefined;
  selector?: string | undefined;
  packageName?: string | undefined;
  format?: 'all' | 'css' | 'ts' | undefined;
  prefix?: string | undefined;
  profile?: string | undefined;
  visualizer?: boolean | undefined;
  allowUnaudited?: boolean | undefined;
  force?: boolean | undefined;
  dryRun?: boolean | undefined;
  knownTreeHash?: string | undefined;
  silent?: boolean | undefined;
  log?: Logger | undefined;
}

export interface CompileTokensResult {
  code: number;
  error?: string | undefined;
  artifacts?: string[] | undefined;
}

export async function compileTokens(opts: CompileTokensOptions): Promise<CompileTokensResult> {
  const {
    tokensDir,
    outDir,
    theme = 'light',
    specPath,
    selector = ':root',
    format: formatArg = 'all',
    packageName,
    prefix,
    profile: profileArg,
    visualizer = false,
    allowUnaudited = false,
    force = false,
    dryRun = false,
    knownTreeHash,
    silent = false,
    log = console.log,
  } = opts;

  if (!['all', 'css', 'ts'].includes(formatArg)) {
    return {
      code: EXIT.USAGE,
      error: `unknown format "${formatArg}" (valid: all, css, ts)`,
    };
  }

  let guide: BuildTokensOptions['guide'];
  let specHash: string | undefined;

  if (specPath !== undefined) {
    if (!existsSync(specPath)) {
      return { code: EXIT.USAGE, error: `tokens config not found: ${specPath}` };
    }
    const loaded = loadSpecOrError(specPath);
    if (!loaded.ok) {
      return { code: EXIT.VALIDATION, error: `tokens config not readable: ${loaded.error}` };
    }
    specHash = specInputHash(loaded.spec);
    guide = guideFromSpec(loaded.spec);
  }

  if (!existsSync(tokensDir)) {
    const lines = [
      `tokens dir not found: ${tokensDir} (run token-engine generate or token-engine sync first)`,
      'state: missing-tokens',
      `evidence: tokens directory not found at ${tokensDir}`,
      'next: token-engine extract --root . --out tokens.config.json (or design-tokens for greenfield)',
      'why: token-engine build requires 3-tier DTCG tokens generated by token-engine generate',
    ];
    return {
      code: EXIT.USAGE,
      error: lines.join('\n'),
    };
  }

  let specBindingStatus: string | undefined;
  if (specHash !== undefined && specPath !== undefined) {
    const binding = checkSpecBinding(tokensDir, specHash);
    specBindingStatus = binding;
    if (!dryRun && binding !== 'match') {
      return {
        code: EXIT.REFUSAL,
        error: `refusing to build: tokens do not match ${specPath} (binding: ${binding}); re-run token-engine generate`,
      };
    }
  }

  const isAllThemes = theme === 'all';
  let allThemes: string[] = [];
  const sDir = semanticDir(tokensDir);
  if (isAllThemes) {
    if (!existsSync(sDir)) {
      return { code: EXIT.USAGE, error: `semantic directory not found: ${sDir}` };
    }
    allThemes = readdirSync(sDir)
      .filter((f) => f.endsWith('.tokens.json'))
      .map((f) => f.replace('.tokens.json', ''));
    if (allThemes.length === 0) {
      return { code: EXIT.USAGE, error: `no semantic themes found in ${sDir}` };
    }
  } else {
    const semanticFile = semanticThemeFile(tokensDir, theme);
    if (!existsSync(semanticFile)) {
      return { code: EXIT.USAGE, error: `theme not found: ${semanticFile}` };
    }
  }

  if (profileArg !== undefined && !(UI_PROFILE_IDS as readonly string[]).includes(profileArg)) {
    return {
      code: EXIT.USAGE,
      error: `unknown profile "${profileArg}" (valid: ${UI_PROFILE_IDS.join(', ')})`,
    };
  }
  const profile = profileArg as UiProfileId | undefined;

  // Stamp check: use fast match if knownTreeHash passed, else full check
  const isPassingStamp = knownTreeHash
    ? auditStampMatches(tokensDir, knownTreeHash)
    : checkAuditStamp(tokensDir) === 'pass';
  const auditStamp = isPassingStamp ? 'pass' : checkAuditStamp(tokensDir);

  const outputNames: string[] = [];
  if (profile !== undefined) {
    outputNames.push(profileFileName(profile));
  } else if (isAllThemes) {
    outputNames.push(...artifactNames({ visualizer, format: formatArg }));
    for (const t of allThemes) {
      outputNames.push(`tokens.${t}.css`, `theme.${t}.css`);
    }
  } else {
    outputNames.push(...artifactNames({ visualizer, format: formatArg }));
  }
  if (packageName !== undefined) {
    outputNames.push('package.json');
  }

  const outputPaths = outputNames.map((name) => join(outDir, name));
  const tamper = checkCssProvenance(outDir);
  const decision = decideWrite({ paths: outputPaths, tamper, force });

  if (dryRun) {
    log(
      profile === undefined
        ? `would build (${theme}) → ${outDir}`
        : `would build profile ${profile} (light + dark) → ${outDir}`,
    );
    if (decision.replaces) log(`provenance: ${tamper.status}`);
    log(`audit stamp: ${auditStamp}`);
    if (specBindingStatus !== undefined) log(`spec binding: ${specBindingStatus}`);
    return { code: EXIT.OK, artifacts: outputPaths };
  }

  const safeError = assertSafeOutDir(outDir, process.cwd());
  if (safeError !== null) {
    return { code: EXIT.REFUSAL, error: safeError };
  }

  if (decision.kind === 'refuse') {
    return {
      code: EXIT.REFUSAL,
      error: reportWriteRefusal(decision, outDir, 'CSS'),
    };
  }
  if (decision.replaces && force && decision.dirty) {
    log('overwriting hand-edited CSS (--force)');
  }

  if (allowUnaudited) {
    log('warning: building without a fresh audit pass (--allow-unaudited)');
  } else if (!isPassingStamp) {
    return {
      code: EXIT.REFUSAL,
      error: `refusing to build: no fresh audit pass for this exact tree (stamp: ${auditStamp}). Run token-engine audit first, or pass --allow-unaudited.`,
    };
  }

  const emittedFiles: string[] = [];

  if (profile !== undefined) {
    const filename = profileFileName(profile as UiProfileId);
    log(`writing ${profile} profile → ${outDir} (theme flag ignored: profiles build light + dark)`);
    const filePath = await buildUiProfile(profile as UiProfileId, tokensDir, outDir.replaceAll('\\', '/'));
    const profileArtifacts: Record<string, string> = { [filename]: filePath };
    publishCssOutputs(outDir, tokensDir, profileArtifacts);
    emittedFiles.push(filePath);
    log(`built profile ${profile} → ${filePath}`);
    return { code: EXIT.OK, artifacts: emittedFiles };
  }

  log(`writing CSS → ${outDir}`);
  const artifactsRecord: Record<string, string> = {};
  if (isAllThemes) {
    const built = await buildMultiThemeTokens({
      tokensDir,
      themes: allThemes,
      outDir,
      prefix,
      selector,
      format: formatArg,
      guide,
      visualizer,
      silent,
    });
    Object.assign(artifactsRecord, built.artifacts);
    emittedFiles.push(...Object.values(built.artifacts));
  } else {
    const source = tokenSourcePatterns(tokensDir, theme);
    const built = await buildTokens({
      source,
      outDir: outDir.replaceAll('\\', '/'),
      prefix,
      selector,
      format: formatArg,
      label: theme,
      guide,
      visualizer,
      silent,
    });
    Object.assign(artifactsRecord, built.artifacts);
    emittedFiles.push(...Object.values(built.artifacts));
    log(
      `built (${theme}) → ${artifactNames({ visualizer, format: formatArg })
        .map((name) => `${outDir}/${name}`)
        .join(', ')}`,
    );
  }

  if (packageName !== undefined) {
    const pkgPath = join(outDir, 'package.json');
    const pkgData = {
      name: packageName,
      version: '0.1.0',
      type: 'module',
      main: './tokens.js',
      types: './tokens.d.ts',
      exports: {
        '.': {
          types: './tokens.d.ts',
          import: './tokens.js',
        },
        './css': './tokens.css',
        './theme': './theme.css',
      },
    };
    writeFileSync(pkgPath, JSON.stringify(pkgData, null, 2) + '\n', 'utf8');
    artifactsRecord['package.json'] = pkgPath;
    emittedFiles.push(pkgPath);
    log(`scaffolded package → ${pkgPath}`);
  }

  if (profile === undefined) {
    const published = publishCssOutputs(outDir, tokensDir, artifactsRecord);
    if (published.missing.length > 0) {
      return {
        code: EXIT.GENERIC,
        error: `build failed: Style Dictionary produced no tokens for ${published.missing.join(', ')}`,
      };
    }
    const cssPath = join(outDir, 'tokens.css');
    const themeCssPath = join(outDir, 'theme.css');
    const designPath = join(outDir, 'DESIGN.md');
    if (existsSync(cssPath) && existsSync(themeCssPath)) {
      const css = readFileSync(cssPath, 'utf8');
      const themeCss = readFileSync(themeCssPath, 'utf8');
      const design = existsSync(designPath) ? readFileSync(designPath, 'utf8') : undefined;
      const problems = verifyGeneratedFiles({
        css,
        theme: themeCss,
        ...(design === undefined ? {} : { design }),
        ...(guide?.primaryHex === undefined ? {} : { expectedPrimaryHex: guide.primaryHex }),
      });
      for (const p of problems) log(`warning: ${p}`);
    }
  }
  return { code: EXIT.OK, artifacts: emittedFiles };
}

export async function runBuild(argv = process.argv.slice(2)): Promise<number> {
  if (hasFlag(argv, '--help')) {
    console.log(usageText('build'));
    return 0;
  }

  const tokensArg = getArg(argv, '--tokens', 'tokens');
  const outArg = getArg(argv, '--out', 'build');
  const theme = getArg(argv, '--theme', 'light');
  const selector = getArg(argv, '--selector', ':root');
  const formatArg = getArg(argv, '--format', 'all') as 'all' | 'css' | 'ts';
  const hasPackage = hasFlag(argv, '--package');
  const packageName = hasPackage ? getArg(argv, '--package') || 'tokens' : undefined;
  const prefix = getArg(argv, '--prefix');
  const force = hasFlag(argv, '--force');
  const dryRun = hasFlag(argv, '--dry-run');
  const visualizer = hasFlag(argv, '--visualizer');
  const specArg = getArg(argv, '--spec');
  const specPath = specArg !== undefined ? fromCwd(specArg) : undefined;
  const profile = getArg(argv, '--profile');
  const allowUnaudited = hasFlag(argv, '--allow-unaudited');

  const result = await compileTokens({
    tokensDir: fromCwd(tokensArg),
    outDir: fromCwd(outArg),
    theme,
    selector,
    format: formatArg,
    packageName,
    prefix,
    profile,
    force,
    dryRun,
    visualizer,
    specPath,
    allowUnaudited,
    log: console.log,
  });

  if (result.error && result.code !== 0) {
    console.error(result.error);
  }

  return result.code;
}

if (isMainModule(import.meta.url, 'build.mjs', 'build.ts')) {
  runBuild().then((code) => process.exit(code));
}
