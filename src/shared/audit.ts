/**
 * audit — Core accessibility and contrast gatekeeper over a 3-tier token tree.
 */
import { existsSync, readFileSync } from 'node:fs';
import {
  auditTokens as evaluateAudit,
  computeDeltaScorecard,
  renderDeltaScorecardTable,
  type AuditResult,
  type PreAuditBaseline,
} from './audit-report.js';
import { EXIT } from './exit-codes.js';
import {
  checkAuditStamp,
  removeAuditStamp,
  specInputHash,
  writeAuditStamp,
} from './guard.js';
import { loadSpecOrError } from './spec.js';
import { semanticDir } from './tokens.js';
import type { Logger } from './types.js';

export interface AuditTokensOptions {
  tokensDir: string;
  specPath?: string | undefined;
  minRatio?: number | undefined;
  minApca?: number | undefined;
  theme?: string | undefined;
  baselinePath?: string | undefined;
  treeCache?: Map<string, unknown> | undefined;
  log?: Logger | undefined;
}

export interface AuditTokensResult {
  code: number;
  error?: string | undefined;
  report?: AuditResult | undefined;
  treeHash?: string | undefined;
}

export function auditTokens(opts: AuditTokensOptions): AuditTokensResult {
  const {
    tokensDir,
    specPath,
    minApca = 60,
    theme = 'both',
    baselinePath,
    treeCache,
    log = console.log,
  } = opts;

  let minRatio = opts.minRatio ?? 4.5;
  let specHash: string | undefined;

  if (specPath !== undefined) {
    const loaded = loadSpecOrError(specPath);
    if (!loaded.ok) {
      return { code: EXIT.VALIDATION, error: loaded.error };
    }
    const spec = loaded.spec;
    if (opts.minRatio === undefined && typeof spec.targets?.minWcagRatio === 'number') {
      minRatio = spec.targets.minWcagRatio;
    }
    specHash = specInputHash(spec);
  }

  if (!existsSync(tokensDir)) {
    const lines = [
      `tokens dir not found: ${tokensDir}`,
      'state: missing-tokens',
      `evidence: tokens directory not found at ${tokensDir}`,
      'next: token-extract --root . --out style-spec.json (or token-style for greenfield)',
      'why: token-audit requires 3-tier DTCG tokens generated by token-math',
    ];
    return {
      code: EXIT.USAGE,
      error: lines.join('\n'),
    };
  }

  const result = evaluateAudit(tokensDir, {
    theme,
    minRatio,
    minApca,
    specHash,
    cache: treeCache,
  });

  const semanticDirectory = semanticDir(tokensDir);
  let baseline: PreAuditBaseline | undefined;
  const candidateBaselinePath = baselinePath ?? '.pre-audit-baseline.json';
  if (existsSync(candidateBaselinePath)) {
    try {
      baseline = JSON.parse(readFileSync(candidateBaselinePath, 'utf8')) as PreAuditBaseline;
    } catch {
      // ignore unreadable baseline
    }
  }

  const primaryReport =
    result.themes[theme] ?? result.themes['light'] ?? Object.values(result.themes)[0];
  const deltaScorecard =
    baseline && primaryReport ? computeDeltaScorecard(baseline, primaryReport) : undefined;

  if (deltaScorecard !== undefined) {
    log(renderDeltaScorecardTable(deltaScorecard));
  }

  const errorLines: string[] = [];
  for (const [name, report] of Object.entries(result.themes)) {
    log(`\n[${name}] min WCAG ratio ${minRatio}:1`);
    for (const pair of report.pairs) {
      const suffix =
        pair.kind === 'border'
          ? ' (border)'
          : pair.kind === 'decorative'
            ? ' (border, decorative)'
            : '';
      const line = `  ${pair.pass ? 'PASS' : 'FAIL'}  ${pair.ratio.toFixed(2)}:1  Lc ${pair.apcaLc.toFixed(1)}  ${pair.foreground} on ${pair.background}${suffix}`;
      log(line);
      if (!pair.pass) {
        errorLines.push(line);
        if (pair.suggestion !== undefined) {
          const sugLine = `        remedy: ${pair.suggestion.path} → ${pair.suggestion.alias} (${pair.suggestion.ratio.toFixed(2)}:1, Lc ${pair.suggestion.apcaLc.toFixed(1)})`;
          log(sugLine);
          errorLines.push(sugLine);
        }
      }
    }
    for (const item of report.unresolvedAliases) {
      const line = `  FAIL  unresolved alias: ${item}`;
      log(line);
      errorLines.push(line);
    }
    for (const item of report.rawValueViolations) {
      const line = `  FAIL  ${item}`;
      log(line);
      errorLines.push(line);
    }
  }

  const provenanceFails =
    result.provenance.status === 'tampered' || result.provenance.status === 'unreadable';
  if (provenanceFails) {
    const parts = [
      ...result.provenance.changed.map((path) => `changed: ${path}`),
      ...result.provenance.missing.map((path) => `missing: ${path}`),
    ];
    const line = `  FAIL  provenance: ${parts.join('; ') || result.provenance.status}`;
    log(line);
    errorLines.push(line);
  } else if (result.provenance.status === 'absent') {
    log('  note: no provenance manifest (tree predates the guard)');
  }

  if (result.specBinding !== undefined && result.specBinding !== 'match') {
    const line = `  FAIL  spec binding: ${result.specBinding} (tokens were generated from a different spec)`;
    log(line);
    errorLines.push(line);
  }

  if (Object.keys(result.themes).length === 0) {
    const line = `  FAIL  no semantic themes found under ${semanticDirectory}`;
    log(line);
    errorLines.push(line);
  }

  log(`\naudit ${result.pass ? 'PASS' : 'FAIL'}`);

  let treeHash: string | undefined;
  if (result.pass) {
    treeHash = writeAuditStamp(tokensDir, {
      minRatio: result.minRatio,
      minApca: result.minApca,
    });
  } else {
    // Only remove the stamp if spec binding mismatched or if the tree is invalid/tampered
    if (result.specBinding === 'mismatch' || checkAuditStamp(tokensDir) !== 'pass') {
      removeAuditStamp(tokensDir);
    }
  }

  return {
    code: result.pass ? EXIT.OK : EXIT.AUDIT,
    report: result,
    treeHash,
    error: result.pass ? undefined : errorLines.join('\n') || 'audit failed',
  };
}
