const lightSources = [
  'tokens/primitive/**/*.tokens.json',
  'tokens/semantic/light.tokens.json',
  'tokens/component/**/*.tokens.json',
];

export default {
  source: lightSources,
  hooks: {
    transforms: {
      'pre-tokens/color-oklch': {
        type: 'value',
        transitive: true,
        filter: (token) => (token.$type ?? token.type) === 'color',
        transform: (token) => {
          const value = token.$value ?? token.value;
          if (
            value !== null &&
            typeof value === 'object' &&
            value.colorSpace === 'oklch'
          ) {
            const [l, c, h] = value.components;
            const fmt = (n, dp) => Number(n.toFixed(dp)).toString();
            const base = `oklch(${fmt(l * 100, 2)}% ${fmt(c, 4)} ${fmt(h, 2)}deg`;
            return value.alpha !== undefined && value.alpha < 1
              ? `${base} / ${value.alpha})`
              : `${base})`;
          }
          return value;
        },
      },
    },
    formats: {
      'pre-tokens/scss-aliases': ({ dictionary }) => {
        const lines = [
          '// Generated by tokens:build — edit tokens/**, not this file.',
          '',
        ];
        for (const token of dictionary.allTokens) {
          const rootTier = token.path[0];
          const varName = token.name;
          if (
            rootTier === 'semantic' ||
            rootTier === 'component' ||
            rootTier === 'layout'
          ) {
            lines.push(`$${varName}: var(--${varName});`);
          } else if (
            rootTier === 'spacing' ||
            rootTier === 'font-size' ||
            rootTier === 'radius' ||
            rootTier === 'rhythm'
          ) {
            const raw = token.$value ?? token.value;
            const val =
              typeof raw === 'object' && raw && 'value' in raw && 'unit' in raw
                ? `${raw.value}${raw.unit}`
                : String(raw);
            lines.push(`$${varName}: ${val};`);
          }
        }
        lines.push('');
        return lines.join('\n');
      },
    },
  },
  platforms: {
    cssLight: {
      transforms: [
        'attribute/cti',
        'name/kebab',
        'time/seconds',
        'html/icon',
        'size/rem',
        'pre-tokens/color-oklch',
        'asset/url',
        'fontFamily/css',
        'cubicBezier/css',
        'strokeStyle/css/shorthand',
        'border/css/shorthand',
        'typography/css/shorthand',
        'transition/css/shorthand',
        'shadow/css/shorthand',
      ],
      buildPath: 'build/',
      files: [
        {
          destination: 'tokens.css',
          format: 'css/variables',
          options: {
            selector: ':root',
            outputReferences: true,
          },
        },
      ],
    },
    scssAliases: {
      transformGroup: 'css',
      buildPath: '__STYLES_ROOT__/abstracts/',
      files: [
        {
          destination: '_variables.scss',
          format: 'pre-tokens/scss-aliases',
        },
      ],
    },
  },
};
