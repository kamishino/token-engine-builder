/**
 * audit — WCAG 2.1 gatekeeper over a 3-tier token tree.
 * Exit 0 = pass, 1+ = contrast failure / unresolved alias / raw value above Tier 1.
 */
import { existsSync, readFileSync } from 'node:fs';
import {
  computeDeltaScorecard,
  type PreAuditBaseline,
} from '../../../shared/audit-report.js';
import { auditTokens } from '../../../shared/audit.js';
import { usageText } from '../../../shared/cli-flags.js';
import { fromCwd, getArg, hasFlag, isMainModule } from '../../../shared/paths.js';

export function runAudit(argv = process.argv.slice(2)): number {
  if (hasFlag(argv, '--help')) {
    console.log(usageText('token-audit/scripts/audit.mjs'));
    return 0;
  }

  const tokensDir = fromCwd(getArg(argv, '--tokens', 'tokens'));
  const theme = getArg(argv, '--theme', 'both');
  const specArg = getArg(argv, '--spec');
  const specPath = specArg !== undefined ? fromCwd(specArg) : undefined;
  const minRatio = argv.includes('--min-ratio') ? Number(getArg(argv, '--min-ratio')) : undefined;
  const minApca = Number(getArg(argv, '--min-apca', '60'));
  const baselineArg = getArg(argv, '--baseline');
  const baselinePath = baselineArg
    ? fromCwd(baselineArg)
    : existsSync(fromCwd('.pre-audit-baseline.json'))
      ? fromCwd('.pre-audit-baseline.json')
      : undefined;
  const asJson = hasFlag(argv, '--json');

  if (asJson && !existsSync(tokensDir)) {
    console.log(
      JSON.stringify(
        {
          state: 'missing-tokens',
          evidence: [`tokens directory not found: ${tokensDir}`],
          next: 'token-extract --root . --out style-spec.json (or token-style for greenfield)',
          why: 'token-audit requires 3-tier DTCG tokens generated by token-math',
        },
        null,
        2,
      ),
    );
    return 1;
  }

  const result = auditTokens({
    tokensDir,
    specPath,
    minRatio,
    minApca,
    theme,
    baselinePath,
    log: asJson ? () => {} : console.log,
  });

  if (asJson && result.report) {
    let baseline: PreAuditBaseline | undefined;
    if (baselinePath && existsSync(baselinePath)) {
      try {
        baseline = JSON.parse(readFileSync(baselinePath, 'utf8')) as PreAuditBaseline;
      } catch {
        // ignore unreadable baseline
      }
    }
    const primaryReport =
      result.report.themes[theme] ?? result.report.themes['light'] ?? Object.values(result.report.themes)[0];
    const deltaScorecard =
      baseline && primaryReport ? computeDeltaScorecard(baseline, primaryReport) : undefined;

    console.log(
      JSON.stringify(
        {
          pass: result.report.pass,
          minRatio: result.report.minRatio,
          minApca: result.report.minApca,
          provenance: result.report.provenance,
          ...(result.report.specBinding === undefined ? {} : { specBinding: result.report.specBinding }),
          ...(deltaScorecard === undefined ? {} : { deltaScorecard }),
          themes: result.report.themes,
        },
        null,
        2,
      ),
    );
  } else if (!asJson && result.error && result.code !== 0 && !result.report) {
    console.error(result.error);
  }

  return result.code === 0 ? 0 : 1;
}

if (isMainModule(import.meta.url, 'audit.mjs', 'audit.ts')) {
  process.exit(runAudit());
}
